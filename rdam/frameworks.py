"""Canonical framework identities projected from Central_Configs v5.0.0 and RDAM's profile.

Eight production technique boundaries bind directly to active ``coe:Cxxxxx`` resources in
``Central_Configs`` v5.0.0 (``../Central_Configs/dist/build/central.sqlite``, verified 2026-11-15);
six formalism-internal identities (``erst``, ``centering``, ``speech_acts``, ``argument_mining``,
``pragma_dialectics``, ``aspic``) are owned by ``rdam`` under ``rdmachine:framework/<name>``.

This module loads the packaged projection ``resources/framework-identities.json`` — generated by
``tools/ontology/project_framework_identities.py`` from ``ontology/data/rdam-providers.yaml`` and
``../Central_Configs/dist/build/central.sqlite`` — so an installed ``rdam`` wheel resolves
framework identities with zero sibling-repository access.
"""

from collections.abc import Mapping
from dataclasses import dataclass
from enum import StrEnum
from functools import cache
from importlib import resources
import json
import re
from types import MappingProxyType
from typing import Final, Literal, cast

from rdam._strict import Sha256Identity, StrictModel, sha256_bytes

FRAMEWORK_SCHEME: Final = "https://steve-allison.github.io/Central_Configs/v5/schema/coe"
_COE_CURIE_RE: Final = re.compile(r"^coe:C[0-9]{5}$")
_COE_COLLECTION_BROADER_PREFIX: Final = f"{FRAMEWORK_SCHEME}#"


class Technique(StrEnum):
    """The framework identities the machine knows, keyed by their boundary/formalism name."""

    RST = "rst"
    ERST = "erst"
    CENTERING = "centering"
    PDTB = "pdtb"
    SDRT = "sdrt"
    SPEECH_ACTS = "speech_acts"
    CLASSICAL_RHETORIC = "classical_rhetoric"
    ARGUMENT_MINING = "argument_mining"
    TOULMIN = "toulmin"
    WALTON = "walton"
    PRAGMA_DIALECTICS = "pragma_dialectics"
    IBIS = "ibis"
    ASPIC = "aspic"
    DUNG = "dung"


BOUNDARY_TECHNIQUES: Final[tuple[Technique, ...]] = (
    Technique.RST,
    Technique.CENTERING,
    Technique.PDTB,
    Technique.SDRT,
    Technique.SPEECH_ACTS,
    Technique.CLASSICAL_RHETORIC,
    Technique.ARGUMENT_MINING,
    Technique.TOULMIN,
    Technique.WALTON,
    Technique.PRAGMA_DIALECTICS,
    Technique.IBIS,
    Technique.ASPIC,
    Technique.DUNG,
)
"""The thirteen production technique boundaries in canonical order. ``erst`` is retained for saved records and workbench evaluation."""

STRUCTURED_INPUT_TECHNIQUES: Final[frozenset[Technique]] = frozenset({Technique.DUNG})
"""Techniques that exclusively analyse a supplied or explicitly derived formal structure rather than raw text."""

DUAL_MODE_TECHNIQUES: Final[frozenset[Technique]] = frozenset({Technique.IBIS, Technique.ASPIC})
"""Techniques that analyse either a source document or a caller-supplied formal structure."""

ACCEPTS_STRUCTURED_INPUT_TECHNIQUES: Final[frozenset[Technique]] = STRUCTURED_INPUT_TECHNIQUES | DUAL_MODE_TECHNIQUES
"""Every technique boundary that accepts caller-supplied ``StructuredInput``."""


@dataclass(frozen=True, slots=True)
class FrameworkIdentity:
    """One framework identity projected from Central_Configs v5.0.0 or RDAM's profile."""

    technique: Technique
    curie: str
    label: str
    broader: str
    scheme: str
    authority: Literal["central_configs", "rdam"] = "central_configs"
    central_concepts: tuple[str, ...] = ()


class FrameworkResolutionError(LookupError):
    """A framework identity is absent from, or inconsistent with, the packaged projection."""


class FrameworkAuthority(StrictModel):
    """Exact authority source and generated projection used for framework identities."""

    authority: Literal["Central_Configs"] = "Central_Configs"
    scheme: str
    source: str
    source_identity: Sha256Identity
    projection_identity: Sha256Identity


@cache
def framework_authority() -> FrameworkAuthority:
    """Identify the installed projection without loading the sibling repository."""
    raw = resources.files("rdam").joinpath("resources/framework-identities.json").read_bytes()
    payload = json.loads(raw)
    if payload.get("scheme") != FRAMEWORK_SCHEME:
        raise FrameworkResolutionError("framework projection names the wrong scheme")
    return FrameworkAuthority(
        scheme=payload["scheme"],
        source=payload["source"],
        source_identity=Sha256Identity(hex_digest=payload["source_sha256"]),
        projection_identity=Sha256Identity(hex_digest=sha256_bytes(raw)),
    )


@cache
def framework_identities() -> Mapping[Technique, FrameworkIdentity]:
    """Load the packaged projection once via explicit dictionary lookup (never CURIE string-splitting)."""

    payload = json.loads(
        resources.files("rdam").joinpath("resources/framework-identities.json").read_text(encoding="utf-8")
    )
    if payload.get("scheme") != FRAMEWORK_SCHEME:
        raise FrameworkResolutionError("framework projection names the wrong scheme")
    concepts = payload.get("concepts")
    if not isinstance(concepts, dict):
        raise FrameworkResolutionError("framework projection has no concepts mapping")
    concept_map = cast(dict[object, object], concepts)
    if set(concept_map) != {technique.value for technique in Technique}:
        raise FrameworkResolutionError("framework projection does not match the registered techniques")

    raw_lookup = payload.get("native_to_curie")
    if not isinstance(raw_lookup, dict):
        raise FrameworkResolutionError("framework projection lacks native_to_curie lookup table")
    native_to_curie = cast(dict[object, object], raw_lookup)

    resolved: dict[Technique, FrameworkIdentity] = {}
    for technique in Technique:
        entry = concept_map.get(technique.value)
        if not isinstance(entry, dict):
            raise FrameworkResolutionError(f"framework projection lacks {technique.value!r}")
        concept = cast(dict[object, object], entry)
        if any(
            not isinstance(concept.get(field), str) or not str(concept[field]).strip()
            for field in ("id", "label", "broader", "in_scheme", "authority")
        ):
            raise FrameworkResolutionError(f"framework identity for {technique.value!r} has invalid text fields")

        curie = cast(str, concept["id"])
        broader = cast(str, concept["broader"])
        authority = cast(str, concept["authority"])
        if native_to_curie.get(technique.value) != curie:
            raise FrameworkResolutionError(
                f"framework native_to_curie mismatch for {technique.value!r}: {native_to_curie.get(technique.value)!r}"
            )
        if concept.get("in_scheme") != FRAMEWORK_SCHEME:
            raise FrameworkResolutionError(f"framework identity for {technique.value!r} is outside the scheme")

        raw_central = concept.get("central_concepts")
        if not isinstance(raw_central, list) or any(not isinstance(item, str) for item in cast(list[object], raw_central)):
            raise FrameworkResolutionError(f"framework identity for {technique.value!r} has invalid central_concepts")
        central_concepts = tuple(cast(list[str], raw_central))
        if len(set(central_concepts)) != len(central_concepts):
            raise FrameworkResolutionError(f"framework identity for {technique.value!r} has duplicate central_concepts")

        if authority == "central_configs":
            if not _COE_CURIE_RE.match(curie):
                raise FrameworkResolutionError(
                    f"Central_Configs framework identity for {technique.value!r} must match ^coe:C[0-9]{{5}}$: {curie}"
                )
            if (
                not broader.startswith(_COE_COLLECTION_BROADER_PREFIX)
                or len(broader) <= len(_COE_COLLECTION_BROADER_PREFIX)
            ):
                raise FrameworkResolutionError(f"framework identity for {technique.value!r} has an invalid broader URI")
            if not central_concepts or curie not in central_concepts or any(
                not _COE_CURIE_RE.match(cid) for cid in central_concepts
            ):
                raise FrameworkResolutionError(
                    f"framework identity for {technique.value!r} has inconsistent central_concepts"
                )
            typed_authority: Literal["central_configs", "rdam"] = "central_configs"
        elif authority == "rdam":
            if curie != f"rdmachine:framework/{technique.value}" or broader != "rdmachine:framework":
                raise FrameworkResolutionError(
                    f"rdam-owned framework identity for {technique.value!r} has invalid id or broader: {curie}"
                )
            if central_concepts:
                raise FrameworkResolutionError(
                    f"rdam-owned framework identity for {technique.value!r} cannot carry central_concepts"
                )
            typed_authority = "rdam"
        else:
            raise FrameworkResolutionError(f"unknown authority {authority!r} for {technique.value!r}")

        resolved[technique] = FrameworkIdentity(
            technique=technique,
            curie=curie,
            label=cast(str, concept["label"]),
            broader=broader,
            scheme=cast(str, concept["in_scheme"]),
            authority=typed_authority,
            central_concepts=central_concepts,
        )
    return MappingProxyType(resolved)


def technique_curie(technique: Technique) -> str:
    """The canonical ``coe:Cxxxxx`` or ``rdmachine:framework/<name>`` identifier for a technique."""

    return framework_identities()[technique].curie


